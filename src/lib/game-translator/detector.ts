/**
 * Game Engine Detector
 * Heuristic signature analysis & AI framework classifier.
 */

import { EngineDetectionResult, GameEngineType } from './types';
import { extractGameTags } from './tag-guard';

export interface FileDescriptor {
  name: string;
  path: string;
  size: number;
  sampleContent?: string;
}

/**
 * Heuristic detector for game engines based on file list and content snippets
 */
export function detectGameEngine(files: FileDescriptor[]): EngineDetectionResult {
  const normalizedPaths = files.map((f) => f.path.replace(/\\/g, '/').toLowerCase());
  const allSamples = files.map((f) => f.sampleContent || '').join('\n');
  const detectedTags = extractGameTags(allSamples);

  // 1. Check RPG Maker MV / MZ
  const rpgMakerFiles = normalizedPaths.filter(
    (p) =>
      p.endsWith('system.json') ||
      p.endsWith('actors.json') ||
      p.includes('data/map') ||
      p.startsWith('data/map') ||
      (p.includes('map') && p.endsWith('.json')) ||
      p.endsWith('commonevents.json') ||
      p.includes('rpg_core.js') ||
      p.includes('rmmz_core.js')
  );

  const hasRpgMakerJsonContent = files.some((f) => {
    if (!f.sampleContent) return false;
    if (
      f.sampleContent.includes('"events"') ||
      f.sampleContent.includes('"tilesetId"') ||
      f.sampleContent.includes('"gameTitle"') ||
      f.sampleContent.includes('"partyMembers"') ||
      f.sampleContent.includes('"armorTypes"')
    ) {
      return true;
    }
    return false;
  });

  if (rpgMakerFiles.length > 0 || hasRpgMakerJsonContent) {
    const isMZ = normalizedPaths.some((p) => p.includes('rmmz')) || allSamples.includes('rmmz_');
    const version = isMZ ? 'RPG Maker MZ' : 'RPG Maker MV / MZ';
    const confidence = rpgMakerFiles.length >= 2 || hasRpgMakerJsonContent ? 0.98 : 0.85;

    return {
      engine: 'rpg_maker_mvmz',
      name: version,
      version: isMZ ? 'MZ' : 'MV/MZ',
      confidence,
      description: 'Hệ thống trích xuất và tái nạp dữ liệu JSON chuẩn RPG Maker (Event 401 Show Text, 102 Choices, Actors, Skills).',
      matchedFiles: rpgMakerFiles.length > 0 ? rpgMakerFiles : files.map((f) => f.path),
      suggestedEncoding: 'UTF-8',
      detectedTags,
      reason: `Phát hiện cấu trúc dữ liệu bản đồ/sự kiện JSON đặc trưng của ${version} (${rpgMakerFiles.length} tệp khớp).`,
    };
  }

  // 2. Check Ren'Py
  const renpyFiles = normalizedPaths.filter(
    (p) => p.endsWith('.rpy') || p.endsWith('.rpyc') || p.includes('/tl/') || p.includes('options.rpy')
  );

  const hasRenpyContent = files.some((f) => {
    const s = f.sampleContent || '';
    return (
      (s.includes('define') && s.includes('Character(')) ||
      s.includes('label start:') ||
      (s.includes('old "') && s.includes('new "')) ||
      /^[a-zA-Z0-9_]+\s+"[^"]+"$/m.test(s)
    );
  });

  if (renpyFiles.length > 0 || hasRenpyContent) {
    return {
      engine: 'renpy',
      name: "Ren'Py Visual Novel Engine",
      version: 'Ren\'Py 7/8',
      confidence: renpyFiles.length >= 1 ? 0.95 : 0.85,
      description: 'Phân tích mã kịch bản Ren\'Py (.rpy), hỗ trợ dịch trực tiếp hoặc xuất cây thư mục game/tl/{ngôn ngữ}.',
      matchedFiles: renpyFiles.length > 0 ? renpyFiles : files.map((f) => f.path),
      suggestedEncoding: 'UTF-8',
      detectedTags,
      reason: "Phát hiện tệp kịch bản .rpy và định dạng hội thoại visual novel đặc trưng của Ren'Py.",
    };
  }

  // 3. Check Unity Localization (XUnity / I2Loc / TextAsset)
  const unityFiles = normalizedPaths.filter(
    (p) =>
      p.endsWith('_autogeneratedtranslations.txt') ||
      p.includes('translation.txt') ||
      p.includes('i2languages') ||
      p.includes('streamingassets') ||
      p.endsWith('assembly-csharp.dll') ||
      p.includes('bepinex')
  );

  const hasUnityKeyValueContent = files.some((f) => {
    const s = f.sampleContent || '';
    const lines = s.split('\n').filter((l) => l.trim().length > 0);
    const kvCount = lines.filter((l) => l.includes('=') && !l.startsWith('#')).length;
    return lines.length > 2 && kvCount / lines.length > 0.6;
  });

  if (unityFiles.length > 0 || hasUnityKeyValueContent) {
    return {
      engine: 'unity_localization',
      name: 'Unity Localization / TextAssets',
      version: 'Unity / XUnity.AutoTranslator',
      confidence: unityFiles.length > 0 ? 0.92 : 0.8,
      description: 'Xử lý tệp cấu hình ngôn ngữ Unity, bảng CSV/TSV I2 Localization hoặc key-value XUnity AutoTranslator.',
      matchedFiles: unityFiles.length > 0 ? unityFiles : files.map((f) => f.path),
      suggestedEncoding: 'UTF-8 (hoặc UTF-8 with BOM)',
      detectedTags,
      reason: 'Phát hiện tệp từ điển XUnity hoặc cấu hình Localization Key-Value của Unity.',
    };
  }

  // 4. Check Godot
  const godotFiles = normalizedPaths.filter(
    (p) => p.endsWith('.godot') || p.endsWith('.tscn') || p.endsWith('.tres')
  );
  if (godotFiles.length > 0) {
    return {
      engine: 'godot',
      name: 'Godot Engine',
      version: 'Godot 3/4',
      confidence: 0.9,
      description: 'Cấu trúc tệp tài nguyên và PO localization của Godot.',
      matchedFiles: godotFiles,
      suggestedEncoding: 'UTF-8',
      detectedTags,
      reason: 'Phát hiện tệp dự án Godot (.godot, .tscn).',
    };
  }

  // 5. Check Generic JSON
  const hasValidJson = files.some((f) => {
    if (!f.sampleContent) return false;
    try {
      JSON.parse(f.sampleContent);
      return true;
    } catch {
      return false;
    }
  });

  if (hasValidJson) {
    return {
      engine: 'generic_json',
      name: 'Generic JSON Localization',
      confidence: 0.75,
      description: 'Định dạng JSON chứa từ điển văn bản trò chơi hoặc tệp i18n chuẩn.',
      matchedFiles: normalizedPaths.filter((p) => p.endsWith('.json')),
      suggestedEncoding: 'UTF-8',
      detectedTags,
      reason: 'Phát hiện các tệp JSON hợp lệ chứa dữ liệu văn bản.',
    };
  }

  // 6. Generic Text / PO / CSV
  return {
    engine: 'generic_text',
    name: 'Generic Game Text / Key-Value',
    confidence: 0.65,
    description: 'Dữ liệu văn bản dòng đôi hoặc bảng chuỗi thông thường.',
    matchedFiles: files.map((f) => f.path),
    suggestedEncoding: 'UTF-8',
    detectedTags,
    reason: 'Định dạng văn bản thông thường hoặc cần AI hỗ trợ nhận diện sâu hơn.',
  };
}

/**
 * Generate AI prompt for advanced framework identification when files are unusual
 */
export function buildAIEnginePrompt(files: FileDescriptor[]): string {
  const structureSummary = files
    .slice(0, 15)
    .map((f) => `- ${f.path} (${f.size} bytes)`)
    .join('\n');

  const snippetSummary = files
    .slice(0, 3)
    .filter((f) => f.sampleContent)
    .map((f) => `### File: ${f.path}\n\`\`\`\n${(f.sampleContent || '').slice(0, 500)}\n\`\`\``)
    .join('\n\n');

  return `Hãy phân tích cấu trúc tệp trò chơi sau đây và xác định:
1. Engine game (RPG Maker MV/MZ/XP/VX, Ren'Py, Unity, Godot, Wolf RPG, Visual Novel, hay custom framework)?
2. Đâu là các khóa văn bản thoại cần dịch (dialogue text) so với mã logic/cấu hình?
3. Các quy tắc escape code và biến (ví dụ \\V[1], {i}, [name], %s) cần bảo toàn?

Cấu trúc thư mục:
${structureSummary}

Nội dung trích mẫu:
${snippetSummary}

Trả về kết quả dưới định dạng JSON:
{
  "engine": "rpg_maker_mvmz" | "renpy" | "unity_localization" | "godot" | "generic_json" | "generic_text",
  "name": "Tên engine",
  "confidence": 0.95,
  "translatablePatterns": ["pattern"],
  "escapeCodes": ["code"]
}`;
}
