/**
 * Ren'Py Script Parser & Re-injector
 * Parses .rpy dialogue statements and string translations.
 */

import { TranslatableSegment } from '../types';
import { extractGameTags } from '../tag-guard';

/**
 * Extract translatable segments from Ren'Py .rpy script
 */
export function extractRenpySegments(
  fileName: string,
  rawScript: string
): TranslatableSegment[] {
  const segments: TranslatableSegment[] = [];
  const lines = rawScript.split('\n');

  // Match dialogue lines:
  // e "Hello, [player_name]! Welcome to the game."
  // or narration: "The wind was blowing softly."
  // or old "..." / new "..."
  const dialogueRegex = /^(\s*)(?:([a-zA-Z0-9_]+)\s+)?"((?:[^"\\]|\\.)*)"(\s*(?:#.*)?)$/;
  const oldStringRegex = /^\s*old\s+"((?:[^"\\]|\\.)*)"/;

  lines.forEach((line, lineIdx) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;

    // Check dialogue or narration
    const match = line.match(dialogueRegex);
    if (match) {
      const indent = match[1] || '';
      const speaker = match[2] || undefined;
      const rawText = match[3] || '';

      // Skip common non-dialogue statements that have quotes (like image "..." or scene "...")
      if (
        speaker &&
        [
          'image',
          'scene',
          'show',
          'hide',
          'play',
          'stop',
          'voice',
          'jump',
          'call',
          'define',
          'default',
          'python',
          '$',
        ].includes(speaker)
      ) {
        return;
      }

      if (rawText.trim().length > 0) {
        // Unescape internal \"
        const cleanText = rawText.replace(/\\"/g, '"');
        segments.push({
          id: `${fileName}:line_${lineIdx + 1}`,
          file: fileName,
          original: cleanText,
          translation: '',
          speaker: speaker || 'Dẫn truyện',
          context: speaker
            ? `Thoại của [${speaker}] tại dòng ${lineIdx + 1}`
            : `Lời dẫn truyện tại dòng ${lineIdx + 1}`,
          status: 'untranslated',
          tags: extractGameTags(cleanText),
          meta: {
            lineIdx,
            indent,
            speaker,
          },
        });
      }
      return;
    }

    // Check old "..." string localization in Ren'Py
    const oldMatch = line.match(oldStringRegex);
    if (oldMatch) {
      const cleanText = oldMatch[1].replace(/\\"/g, '"');
      if (cleanText.trim().length > 0) {
        segments.push({
          id: `${fileName}:line_${lineIdx + 1}:string`,
          file: fileName,
          original: cleanText,
          translation: '',
          context: `Chuỗi UI / Menu tại dòng ${lineIdx + 1}`,
          status: 'untranslated',
          tags: extractGameTags(cleanText),
          meta: {
            lineIdx,
            isOldNewPair: true,
          },
        });
      }
    }
  });

  return segments;
}

/**
 * Re-inject translations into Ren'Py script in-place
 */
export function injectRenpyTranslations(
  rawScript: string,
  segments: TranslatableSegment[]
): string {
  const transMap = new Map<number, string>();
  for (const s of segments) {
    if (s.translation.trim().length > 0 && typeof s.meta.lineIdx === 'number') {
      transMap.set(s.meta.lineIdx, s.translation);
    }
  }

  const lines = rawScript.split('\n');

  lines.forEach((line, lineIdx) => {
    const trans = transMap.get(lineIdx);
    if (!trans) return;

    // Escape double quotes inside translated string
    const escapedTrans = trans.replace(/"/g, '\\"');

    // Replace the quoted text in that line
    const replaced = line.replace(
      /"((?:[^"\\]|\\.)*)"/,
      `"${escapedTrans}"`
    );
    lines[lineIdx] = replaced;
  });

  return lines.join('\n');
}

/**
 * Generate standard Ren'Py translation block file (e.g. game/tl/vietnamese/script.rpy)
 */
export function generateRenpyTranslationFile(
  language: string,
  segments: TranslatableSegment[]
): string {
  const output: string[] = [
    `# Ren'Py Translation File for [${language}]`,
    `# Auto-generated by GameLingo AI`,
    '',
    `translate ${language} strings:`,
  ];

  for (const seg of segments) {
    const orig = seg.original.replace(/"/g, '\\"');
    const trans = (seg.translation || seg.original).replace(/"/g, '\\"');
    output.push(`    old "${orig}"`);
    output.push(`    new "${trans}"`);
    output.push('');
  }

  return output.join('\n');
}
